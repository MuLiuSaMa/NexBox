export type OptimizerCategory =
  | "gaming"
  | "gpu"
  | "performance"
  | "privacy"
  | "ai"
  | "services"
  | "disk"
  | "apps"
  | "network"
  | "explorer"
  | "audio";

export interface OptimizerItem {
  id: string;
  regName: string;
  category: OptimizerCategory;
  icon: ComponentType<{ size?: number; strokeWidth?: number }>;
  color: string;
  titleKey: string;
  descKey: string;
  /** 风险等级：low 低风险 | medium 中风险 | high 高风险 */
  risk: "low" | "medium" | "high";
  /** 渲染类型：toggle（默认开关）| select（下拉选择） */
  type?: "toggle" | "select";
  /** select 类型的选项列表 */
  options?: {
    value: string;
    labelKey: string;
    regName: string;
  }[];
  /** select 类型的默认选中值 */
  defaultSelectValue?: string;
}

